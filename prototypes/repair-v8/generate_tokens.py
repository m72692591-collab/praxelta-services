"""Generate CSS platform variables from the typed token source."""
from pathlib import Path
from tokens import TOKENS

ROOT = Path(__file__).parent
lines = ["/* Generated by generate_tokens.py; edit tokens.py instead. */", ":root {"]
for group, values in TOKENS.items():
    for name, value in values.items():
        lines.append(f"  --{group}-{name}: {value};")
lines += ["  --gradient-brand: linear-gradient(120deg, var(--colors-blue), var(--colors-violet) 55%, var(--colors-magenta));", "  --gradient-action: linear-gradient(110deg, #087886, #1256B0, #4D27A8);", "}", ""]
(ROOT / "tokens.css").write_text("\n".join(lines), encoding="utf-8")
