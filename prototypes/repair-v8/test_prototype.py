from html.parser import HTMLParser
from pathlib import Path
import ast
import re

ROOT = Path(__file__).parent
HTML = (ROOT / "index.html").read_text(encoding="utf-8")
JS = (ROOT / "app.js").read_text(encoding="utf-8")
CSS = (ROOT / "app.css").read_text(encoding="utf-8")
TOKENS_CSS = (ROOT / "tokens.css").read_text(encoding="utf-8")

class StrictParser(HTMLParser):
    def error(self, message):
        raise AssertionError(message)

def test_html_and_typed_token_source_parse():
    StrictParser().feed(HTML)
    ast.parse((ROOT / "tokens.py").read_text(encoding="utf-8"))

def test_required_product_views_are_present():
    for view in ("home", "request", "estimate", "parts", "checkout", "split", "order", "master", "supplier", "admin"):
        assert f'data-view="{view}"' in HTML

def test_required_system_states_are_implemented():
    for state in ("loading", "empty", "error", "blocked", "offline", "stale", "partial", "refund", "dispute"):
        assert f'value="{state}"' in HTML
        assert re.search(rf"\b{state}:\s*\[", JS)

def test_demo_has_no_network_or_persistence_routes():
    combined = HTML + JS
    assert not re.search(r"https?://", combined, re.IGNORECASE)
    for token in ("fetch(", "XMLHttpRequest", "WebSocket", "sendBeacon", "localStorage", "sessionStorage"):
        assert token not in combined
    assert "connect-src 'none'" in HTML

def test_no_card_secret_or_contact_collection():
    lowered = HTML.lower()
    for forbidden in ('type="email"', 'type="tel"', 'name="pan"', 'name="cvv"', 'name="cvc"', "secretkey", "terminalkey", "rebillid"):
        assert forbidden not in lowered

def test_capability_driven_checkout_fails_closed():
    checkout = HTML.split('data-view="checkout"', 1)[1].split('data-view="split"', 1)[0]
    assert "CAPABILITY: UNKNOWN" in checkout
    assert "не подтверждён" in checkout
    assert 'disabled aria-disabled="true"' in checkout
    assert "Оплата прошла" not in HTML

def test_transparency_copy_and_no_forbidden_marketing_metrics():
    for text in ("Публичная цена", "Партнёрская цена", "Вознаграждение не добавляется", "Диапазон, не итоговая цена", "Демо не считает заказ оплаченным"):
        assert text in HTML
    for forbidden in ("30 минут", "96%", "1 год", "24/7"):
        assert forbidden not in HTML

def test_accessibility_and_motion_contract():
    assert 'lang="ru"' in HTML
    assert 'aria-live="polite"' in HTML
    assert 'aria-label="Основная навигация"' in HTML
    assert ":focus-visible" in CSS
    assert "prefers-reduced-motion:reduce" in CSS
    assert "min-width:44px" in CSS and "min-height:44px" in CSS

def test_kopecks_are_the_runtime_money_source():
    assert 'data-kopecks-min="240000"' in HTML
    assert "formatKopecks" in JS
    assert "Math.trunc(value / 100)" in JS

def test_generated_tokens_match_source():
    assert TOKENS_CSS.startswith("/* Generated by generate_tokens.py")
    for value in ("#050A1B", "#1C7DFF", "#28E7F7", "#7A42FF", "#F33DDF", "#BEFF3B", "#FFCC5C", "#FF6680"):
        assert value in TOKENS_CSS

def test_prototype_is_clearly_non_production():
    assert "КОНЦЕПТ · ДАННЫЕ НЕ ОТПРАВЛЯЮТСЯ · ПЛАТЕЖЕЙ НЕТ" in HTML
    assert "демо · не production" in HTML
    assert "CONCEPT_NOT_PRODUCTION" in HTML
